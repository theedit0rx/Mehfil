const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const sandbox = {console, Date, globalThis: null}; sandbox.globalThis = sandbox;
vm.runInNewContext(fs.readFileSync(__dirname+'/web/history-core.js','utf8'), sandbox);
const H = sandbox.MehfilHistory;
const saved = {};
const local = {getItem:k => saved[k]??null, setItem:(k,v)=>{saved[k]=v;}};
const h = H.create(local);const t = {id:'test-song',title:'Ya Nabi',artist:'Nusrat',categories:['nabi','qawwali']};
const d = new Date(2026, 9, 23,23,59,58).getTime();
h.recordStart(t,d);h.recordSeconds(t,d,5);
assert(Math.abs(h.day('2026-10-23').seconds - 2) < 0.001);
assert(Math.abs(h.day('2026-10-24').seconds - 3) < 0.001);
assert.equal(h.day('2026-10-23').plays, 1);
assert.equal(h.day('2026-10-24').plays, 0);
assert.equal(h.month('2026-10').activeDays,2);
assert.equal(h.month('2026-10').topTracks[0].title,'Ya Nabi');
assert.equal(h.month('2026-10').topCategories[0][0],'nabi');
const h2 = H.create(local);assert(Math.abs(h2.all().seconds - 5)<0.001);
const backup = h2.exportData();h2.clear();assert.equal(h2.all().seconds,0);h2.importData(backup);assert(Math.abs(h2.all().seconds-5)<0.001);
assert.equal(H.weekKey(new Date(2026,9,25)),H.dateKey(new Date(2026,9,19)));
assert.equal(h2.week('2026-10-19').plays,1);
assert.throws(()=>h2.importData({foo:'evil'}));
console.log('PASS: midnight splitting, stats, play starts, categories, week boundaries, persistence and backup restore');
